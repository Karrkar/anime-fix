import { engineReply, extractProfileDelta, sanitizeProfile, type ChatMsg, type RecTitle } from '../src/lib/succubus';

const RECS: RecTitle[] = [
  { title: 'Ван-Пис', genres: 'приключения, фэнтези, сёнэн' },
  { title: 'Твоё имя', genres: 'романтика, драма' },
  { title: 'Тетрадь смерти', genres: 'триллер, детектив' },
  { title: 'Клинок, рассекающий демонов', genres: 'приключения, фэнтези, сёнэн' },
  { title: 'Атака титанов', genres: 'драма, фэнтези' },
];

const profile = sanitizeProfile({ name: 'Артём', favGenres: ['романтика'] });

function show(label: string, userText: string, history: ChatMsg[] = []) {
  const r = engineReply(userText, { history, recs: RECS, profile });
  console.log(`\n[${label}] ты: ${userText}`);
  console.log(`         Лилит: ${r}`);
}


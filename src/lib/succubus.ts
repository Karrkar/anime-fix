const STOPWORDS = new Set([
  'это', 'что', 'как', 'так', 'вот', 'для', 'тебе', 'меня', 'тебя', 'себе', 'чтобы',
  'есть', 'был', 'была', 'быть', 'твой', 'моя', 'твоя', 'мой', 'аниме', 'очень',
  'просто', 'может', 'хочу', 'если', 'когда', 'этот', 'эта', 'какой', 'какая',
]);

function pick<T>(arr: T[], seed = Math.random()): T {
  return arr[Math.floor(seed * arr.length) % arr.length];
}

/** Строчное ядро в начале нового предложения — с заглавной */
function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/** Заглавные на границах предложений внутри реплики («...книгу. И книга») */
function caps(s: string): string {
  return s.replace(/(^|[.!?…]\s+)([а-яёa-z])/g, (_m, p1: string, p2: string) => p1 + p2.toUpperCase());
}

/** Точка в конце фразы, если её там нет (только после буквы/скобки) */
function dot(s: string): string {
  return /[а-яёa-z)]$/i.test(s) ? `${s}.` : s;
}

function timeOpeners(): string[] {
  const h = new Date().getHours();
  if (h >= 5 && h < 12) return OPENERS_MORNING;
  if (h >= 12 && h < 18) return OPENERS_DAY;
  if (h >= 18 && h < 23) return OPENERS_EVENING;
  return OPENERS_NIGHT;
}

/** Вытаскивает 1–2 значимых слова пользователя для отражения в ответе. */
export function mirrorWords(text: string): string[] {
  const words = text
    .toLowerCase()
    .replace(/[^а-яёa-z0-9\s-]/gi, ' ')
    .split(/\s+/)
    .filter(w => w.length >= 5 && !STOPWORDS.has(w));
  return words.slice(0, 2);
}

const GENRE_MAP: Array<[RegExp, string]> = [
  [/романт|любов|лайв|сёдзё/, 'романтика'],
  [/драм/, 'драма'],
  [/боев|сёнэн|сражен|файт/, 'боевик'],
  [/фэнтез|магия|исекай|друго[йм] мире|демон/, 'фэнтези'],
  [/комеди|смешн|юмор/, 'комедия'],
  [/ужас|хоррор|страшн|мистик/, 'мистика и ужасы'],
  [/спорт/, 'спорт'],
  [/детектив|расслед|тайн/, 'детектив'],
  [/триллер|психолог/, 'триллер'],
  [/меха|робот/, 'меха'],
  [/школ|академ/, 'школьные истории'],
  [/повседневн|slice/, 'повседневность'],
  [/приключ/, 'приключения'],
  [/фантаст|sci-?fi|космос/, 'фантастика'],
];

export function detectGenre(text: string): string | null {
  const t = text.toLowerCase();
  for (const [re, label] of GENRE_MAP) if (re.test(t)) return label;
  return null;
}

export type Intent =
  | 'greeting' | 'who' | 'how-are-you' | 'name' | 'rec' | 'lewd' | 'insult'
  | 'thanks' | 'bye' | 'help' | 'bored' | 'flirt' | 'succubus' | 'repeat' | 'question' | 'default';

export function classify(text: string, lastUserMsg?: string): Intent {
  const t = text.toLowerCase().trim();
  if (lastUserMsg && t === lastUserMsg.toLowerCase().trim() && t.length > 0) return 'repeat';
  if (/(хентай|hentai|18\+|секс|раздень|голая|эроти|порн|интим|похот|хочу тебя|возьми меня|страстн)/i.test(t)) return 'lewd';
  if (/(тупая|дура|идиот|ненави[дж]у тебя|заткни|иди на|отвали|бесполезн)/i.test(t)) return 'insult';
  if (/(меня зовут\s+|я\s*[—-]?\s*это\s*)/i.test(t)) return 'name';
  if (/(кто ты|что ты такое|ты кто|расскажи о себе|ты настоящ|ты живая|ты робот|ты бот|ты ии|ты человек)/i.test(t)) return 'who';
  if (/(как\s*(ты|дела|жизнь|настроение)|что нового|чем занята)/i.test(t)) return 'how-are-you';
  if (/(скучно|развесели|нечего делать|заскучал)/i.test(t)) return 'bored';
  if (/(посовет|рекоменд|что (бы |б)посмотреть|что посмотреть|подскаж(и|и что)|дай что-нибудь|нравится ли тебе)/i.test(t)) return 'rec';
  if (/(подписк|оплат|цена|руб|сколько стоит|бесплатн|регистрац|как смотреть|как скачать|где серии|где найти|как включить)/i.test(t)) return 'help';
  // Благодарность срабатывает только на короткое «спасибо» без встречного
  // вопроса — иначе Лилит пропускала бы мимо ушей «спасибо, а ты чем занята?»
  if (/(спасибо|благодар|спс|пасиб|thanks)/i.test(t) && !/\?/.test(t) && t.split(/\s+/).length <= 4) return 'thanks';
  if (/^(пока|до встречи|прощай|спокойной ночи|споки|доброй ночи|бай)/i.test(t)) return 'bye';
  if (/(привет|хай|здравств|добрый (день|вечер|утро)|салют|йоу|^ку\b|хеллоу)/i.test(t)) return 'greeting';
  if (/(суккуб|демоница|демон|дьявол|бес|черт)/i.test(t)) return 'succubus';
  if (/(красив|мила|нравишься|люблю тебя|поцел|свидан|встретимся|будь моей|жена)/i.test(t)) return 'flirt';
  if (/\?\s*$/.test(t)) return 'question';
  return 'default';
}

export function extractName(text: string): string | null {
  const m = text.match(/меня зовут\s+([А-ЯЁа-яёA-Za-z-]{2,20})/i);
  if (m) {
    const n = m[1];
    return n.charAt(0).toUpperCase() + n.slice(1).toLowerCase();
  }
  return null;
}

function fmtRecs(recs: RecTitle[], genreLabel: string | null, usedTexts = ''): string {
  if (!recs.length) return '';
  const intro = genreLabel
    ? pickFresh(REC_INTROS, usedTexts).replace('%s', genreLabel)
    : pickFresh(['Слушай внимательно, малыш 😏', 'Мой вердикт', 'Держи проверенное 💜'], usedTexts);
  // 3 случайных тайтла из живого каталога — не простыня
  const shuffled = [...recs].sort(() => Math.random() - 0.5).slice(0, 3);
  const titles = shuffled.map(r => `«${r.title}»`).join(', ');
  return `${intro} ${titles}. ${pickFresh(REC_TAILS, usedTexts)}`;
}

export interface EngineContext {
  history: ChatMsg[];
  recs: RecTitle[];
  now?: Date;
}

/** Свежий выбор: не берём вариант, который уже звучал в недавних репликах Лилит. */
function pickFresh(arr: string[], usedTexts: string, seed = Math.random()): string {
  const fresh = arr.filter(x => !usedTexts.includes(x));
  return pick(fresh.length ? fresh : arr, seed);
}

/** Тема свободного разговора (работа/ночь/настроение/любовь/еда/игры...) */
function detectTopic(text: string): string[] | null {
  for (const [re, lines] of TOPICS) if (re.test(text)) return lines;
  return null;
}

/** Ядро движка: собирает уникальную реплику из интента + контекста + случайности. */
export function engineReply(userText: string, ctx: EngineContext): string {
  // История содержит и текущее сообщение — для детекта повтора сравниваем
  // с предыдущими репликами пользователя (без текущей).
  const prior = [...ctx.history];
  const last = prior[prior.length - 1];
  if (last && last.role === 'user' && last.content.toLowerCase().trim() === userText.toLowerCase().trim()) prior.pop();
  const intent = classify(userText, [...prior].reverse().find(m => m.role === 'user')?.content);
  const mirrors = mirrorWords(userText);
  const r1 = Math.random(), r2 = Math.random(), r3 = Math.random(), r4 = Math.random();
  const shape = Math.random();

  // Анти-повтор: шаблоны, прозвучавшие в последних репликах Лилит, не выбираем
  const used = ctx.history
    .filter(m => m.role === 'assistant')
    .slice(-6)
    .map(m => m.content)
    .join('\n');
  const pf = (arr: string[], seed: number): string => pickFresh(arr, used, seed);

  const action = r4 < 0.45 ? `${pf(ACTIONS, r1)} ` : '';
  const tease = mirrors.length ? pf(TEASE_MIRROR, r2).replace('%s', mirrors[0]) : pf(INTEREST_REACT, r2);
  const question = pf(Q_FOLLOWUPS, r3);
  const core = pf(shape < 0.45 ? CONVO_CORES : FLIRTY_CORE, r2);
  const pet = pick(PET_NAMES, r3);

  const nameFromHistory = (() => {
    for (let i = ctx.history.length - 1; i >= 0; i--) {
      if (ctx.history[i].role !== 'user') continue;
      const n = extractName(ctx.history[i].content);
      if (n) return n;
    }
    return null;
  })();
  const name = extractName(userText) || nameFromHistory;
  const address = name ? `, ${name}` : '';

  // Свободная беседа (default/question): тема → живая реакция по теме,
  // иначе — реакция на слова + немного о себе + встречный вопрос.
  const converse = (): string => {
    const topic = detectTopic(userText);
    if (topic) return `${action}${pf(topic, r2)}`;
    if (shape < 0.4) return `${action}${tease}${address}. ${caps(core)}. ${question}`;
    if (shape < 0.7) return `${action}${tease}${address}. Отвечу не бесплатно, ${name || pet} 😏 ${question}`;
    return `${action}${caps(core)}${address ? `, ${name}` : `, ${pet}`}. ${question}`;
  };

  switch (intent) {
    case 'repeat':
      return `${action}Повторяешься, ${pet}${address} 😏 Я всё слышала с первого раза. Попробуй с другого бока: ${question}`;
    case 'lewd':
      return `${action}${pf(LEWD_DEFLECT, r1)}`;
    case 'insult':
      return pf(INSULT_RETORT, r1);
    case 'name':
      return `${action}«${name}» — записала навсегда. У суккубов память на имена, как у людей на боль 😏 Ну что, ${name}, ${question.toLowerCase()}`;
    case 'who':
      return `${action}${pf(WHO_CORE, r1)} ${question}`;
    case 'how-are-you':
      return `${action}${pf(HOW_ARE_YOU, r1)}`;
    case 'rec': {
      const genre = detectGenre(userText);
      const recs = fmtRecs(ctx.recs, genre, used);
      if (recs) return `${action}${recs}`;
      return `${action}${pf(BORED_CORE, r1)}`;
    }
    case 'bored': {
      const base = dot(pf(BORED_CORE, r1));
      const bonus = ctx.recs.length && shape < 0.5
        ? ` Кстати, наудачу: «${pick(ctx.recs, r2).title}» — глянь, не прогадаешь`
        : '';
      return `${action}${base}${bonus}${shape >= 0.5 ? ` ${question}` : ''}`;
    }
    case 'help':
      return `${action}${pf(HELP_CORE, r1)}`;
    case 'thanks':
      return pf(THANKS_REPLY, r1);
    case 'bye':
      return pf(BYE_REPLY, r1);
    case 'greeting': {
      const op = pf(timeOpeners(), r1);
      const opBang = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}.!?)»]$/u.test(op) ? op : `${op}!`;
      return shape < 0.4
        ? `${action}${opBang}${address} ${question}`
        : `${action}${opBang}${address} ${caps(core)}. ${question}`;
    }
    case 'succubus':
      return `${action}${pf(SUCCUBUS_REPLY, r1)}`;
    case 'flirt':
      return `${action}${pf(FLIRT_REPLY, r1)}`;
    case 'question':
    case 'default':
      return converse();
  }
}

// ─── Промпт-подсказка каталога (для LLM) ────────────────────────────────

export function buildCatalogHint(recs: RecTitle[]): string {
  if (!recs.length) return '— (каталог временно недоступен, общайся общими знаниями об аниме, но честно признайся, что не видишь текущий каталог)';
  return recs
    .slice(0, 40)
    .map(r => `• ${r.title}${r.genres ? ` (${r.genres})` : ''}`)
    .join('\n');
}

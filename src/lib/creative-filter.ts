/**
 * Фильтр «только арты» для вкладки «Креатив».
 *
 * Проблема: TG-каналы публикуют не только арты — текстовые посты, анонсы
 * стримов, кросс-промо списками ссылок, «публикации» сервиса и служебные
 * записи. Пользователь просил в ленте ИСКЛЮЧИТЕЛЬНО тематические арты.
 *
 * Две функции:
 *   isArtPost(raw)      — пост merits попадания в ленту? (false = мусор)
 *   sanitizeCaption(s)  — вычистить из подписи промо-футеры автора
 *                        (Предложка/Заказать/Поддержать/VIP-выпки и ссылки),
 *                        сам арт-пост при этом СОХРАНЯЕТСЯ.
 *
 * Правила откалиброваны по реальному корпусу из 10 каналов (сентябрь 2026):
 *  - simple_elf: арты + VK-VIP промо в подписи → оставляем, подпись чистим;
 *  - stefanfalkokmoth: 295/600 постов с футером «Предложка|Заказать|Поддержать»;
 *  - genshin3416/pornofullp: кросс-промо списками t.me-ссылок (подпись после
 *    вырезания ссылок пуста) → мусор;
 *  - neuroart1215: анонсы стримов/прохождений игр с youtube-ссылками → мусор;
 *  - каналы ai_harem и StefanFalkokAI целиком не-артовые — удалены из
 *    TG_CHANNELS отдельно (сервис-промо и ИИ-новости).
 *
 * Модуль ЧИСТЫЙ (без импортов) — используется из creative-store (синк и
 * нормализация) и портирован в scripts/cleanup_creative.mjs (чистка БД).
 */

// ─── URL в подписи ─────────────────────────────────────────────────────────

/**
 * Любая ссылка: с протоколом, голый t.me/vk.com/…, а также общий случай
 * «слово.домен/…» (civitai.com/user/x, boosty.to/… и т.п.).
 * ВАЖНО: \w не покрывает кириллицу — классы букв задаются явно.
 */
const URL_RE = new RegExp(
  [
    'https?://\\S+',
    '(?:^|\\s)(?:t\\.me|vk\\.com|vk\\.ru|clck\\.ru|bit\\.ly|youtu\\.be)/\\S+',
    '(?:^|\\s)[a-z0-9-]+\\.(?:com|ru|net|org|me|io|red|gg|xyz|to|app|dev|art|fun|link|su|pro|site|online|club|page|pics|gallery|boosty)\\/?\\S*',
  ].join('|'),
  'gi',
);

/** Подпись без ссылок (ссылки заменены пробелами). */
function stripUrls(cap: string): string {
  return cap.replace(URL_RE, ' ');
}

/** Считаем «значимые» символы: буквы/цифры любых алфавитов. */
function countLetters(s: string): number {
  return (s.match(/[\p{L}\p{N}]/gu) || []).length;
}

/** Числовые HTML-сущности (&#33; и т.п.) — старый парсер их не декодировал. */
function decodeNumericEntities(s: string): string {
  return s
    .replace(/&#(\d+);/g, (_, d) => {
      try { return String.fromCodePoint(Number(d)); } catch { return ' '; }
    })
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => {
      try { return String.fromCodePoint(parseInt(h, 16)); } catch { return ' '; }
    })
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&');
}

// ─── DROP: пост является рекламой/публикацией, а не артом ──────────────────

/**
 * Жёсткие маркеры «это рекламный/не-артовый пост».
 * ВАЖНО №1: сюда НЕ включать футерные слова (випка, вступить, заказать…) —
 * они встречаются в подписях НАСТОЯЩИХ артов и вычищаются sanitizeCaption.
 * ВАЖНО №2: маркеры проверяются ПОСЛЕ чистки подписи (см. isArtPost) —
 * «Стримы: youtube.com/…» в футере арт-поста не делает пост не-артом,
 * а вот «Стрим в Таверне…» в основном тексте — делает.
 * URL-формы (youtube.com и т.п.) сюда не входят: ссылки вырезаются раньше.
 */
const AD_HARD_RE = new RegExp(
  [
    '\\bреклам[аыуе]\\b',            // «реклама», «рекламы»
    'спонсор',
    'промокод',
    'промо\\s+код',
    '\\bказино\\b',
    'букмекер',
    'ставк[а-яё]*\\s+на\\s',         // ставки на спорт
    'подпишись',
    'подписывайся',
    'подписывайтесь',
    'скидк[аи]',                     // «скидка» — коммерция
    'стрим',                         // анонсы стримов/стримить игру
    'ютуб',                          // текстовые упоминания (URL вырезаны)
    'твич',
    'прохожден',                     // летсплеи/прохождения игр
    '(?:новый|второй|запасной|резервный)\\s+канал',   // миграции каналов
    'канал\\s+заблокирован',
    'технические\\s+проблемы',
    'сервис\\s+(?:восстановлен|работает)',
    'мы\\s+переехали',
    'страничк[а-яё]*\\s+на\\s',      // «появилась страничка на …»
    'по\\s+вопросам\\s+(?:рекламы|сотрудничества|размещения)',
  ].join('|'),
  'i',
);

/**
 * Является ли пост тематическим артом.
 * false → пост не попадает в ленту «Креатив» (и не хранится).
 *
 * Критерии (по убыванию приоритета):
 *   1) без визуала (фото/постер) — текст, стикер, голос, служебное — не арт;
 *   2) кросс-промо списком: ссылок 2+ и, если ссылки вырезать, от подписи
 *      почти ничего не остаётся (только эмодзи/разделители);
 *      посты с 2+ ссылками, но содержательным текстом (донат/VIP-футер
 *      simple_elf, neuroart1215) — оставляем: футер вычистится, арт настоящий;
 *   3) жёсткие рекламные/не-артовые маркеры — но по ОЧИЩЕННОЙ подписи:
 *      футер «Поддержать… 📺 Стримы: youtube…» срезается ДО проверки,
 *      поэтому стрим-слова в футере не топят арт-пост.
 */
export function isArtPost(raw: {
  photos?: string[];
  videoPoster?: string;
  caption?: string;
}): boolean {
  const photos = raw.photos || [];
  // 1) Без визуала — не арт.
  if (!photos.length && !raw.videoPoster) return false;
  const cap = decodeNumericEntities(raw.caption || '').replace(/\s+/g, ' ').trim();
  // Чистый арт без подписи — идеальный случай.
  if (!cap) return true;
  // 2) Кросс-промо списком: ссылок 2+, а текста без них нет.
  const urls = cap.match(URL_RE);
  if (urls && urls.length >= 2) {
    const letters = countLetters(stripUrls(cap));
    if (letters < 6) return false;
  }
  // 3) Жёсткие маркеры — по подписи без футеров/ссылок.
  const cleaned = sanitizeCaption(cap);
  if (cleaned && AD_HARD_RE.test(cleaned)) return false;
  return true;
}

// ─── SANITIZE: чистка подписи арт-поста от промо-футеров ───────────────────

/**
 * Футерные ключевые слова: в чанке подписи всё от ключевого слова до конца
 * чанка — промо автора (Предложка, Заказать, Поддержать, Приватка, VIP…).
 * Подобраны по реальным футерам stefanfalkokmoth / simple_elf / neuroart1215.
 * 'vip' НЕ используем голым (режет имена вроде Viper) — только связки.
 */
const FOOTER_KEYWORDS: string[] = [
  'предложк',                          // Предложка
  'заказать',                          // Заказать арт/лору, картинку
  'поддержа',                          // Поддержать канал
  'забусти',                           // Забустить канал
  'приватк',                           // Доступ в приватку
  'доступ в',                          // Доступ в приватку/закрытый канал
  'чатик',                             // Наш чатик
  'наш чат',
  'sfw канал',
  'swf канал',
  'бусти',                             // Мой Бусти (Boosty)
  'boosty',
  'випк',                              // випка/Випка
  'vip[- ]?(?:групп|канал|доступ|подписк|раздел|чат)',
  'вступ',                             // Вступить в…
  'фулл альбом',
  'хентай альбом',
  'полный альбом',
  'второй канал',
  'подписывайс',                       // Подписывайся
  'подпишит',                          // Подпишитесь/подпишись
];
// «по вопросам» НЕ футерное слово: «по вопросам рекламы/размещения» —
// маркер рекламного поста (см. AD_HARD_RE), и санитизация не должна
// съедать улику ДО проверки isArtPost.

/** Декоративные разделители футеров (🌐 🔠 🟣 ➡️ 💠) — границы чанков. */
const SEPARATOR_RE = /\s*(?:\uD83C\uDF10|\uD83D\uDD20|\uD83D\uDFE3|\u27A1|\uD83D\uDCA0)\s*/g;

/**
 * Чанки-признаки атрибуции/остатки после вырезания ссылок — целиком вон:
 *  - «где я ещё размещаю арты: …» — стандартный футер neuroart1215;
 *  - голое имя платформы (Civit AI / DeviantArt / Pixiv…) без ссылки.
 */
const CHUNK_DROP_RE: RegExp[] = [
  /где\s+(?:я\s+)?ещ[её]\s+размещаю/i,
  /ссылк[аи]?\s+на\s+(?:все\s+)?(?:мои\s+)?(?:работы|арты|профиль)/i,
  /^(?:civit\s*ai|civitai|deviantart|pixiv|boosty|патреон|patreon|artstation|twitter|телеграм|telegram|тг)$/i,
];

/** Буквенно-цифровой символ любого алфавита. */
const HAS_WORDCHAR_RE = /[\p{L}\p{N}]/u;

/**
 * Вычищает из подписи арт-поста промо-материалы автора:
 *  - все ссылки (атрибуция «где ещё размещаю арты» — шум в ленте артов);
 *  - футерные фразы до конца чанка/предложения (Предложка/Заказать/VIP…);
 *  - скобки с пометками «(закрытая випка)», «(приватная випка)»;
 *  - висящие вводные хвосты, заканчивающиеся «:», осиротевшие разделители,
 *    чисто-эмодзиные и чисто-пунктуационные куски.
 * Пост остаётся в ленте; подпись — только про сам арт.
 */
export function sanitizeCaption(rawCaption: string): string {
  let s = decodeNumericEntities(rawCaption || '').replace(/\s+/g, ' ').trim();
  if (!s) return '';

  // 1) Ссылки — вон.
  s = stripUrls(s);

  // 2) Скобочные пометки промо-доступа — вон целиком.
  s = s.replace(/\([^)]*(?:випк|vip|приватн|закрыт|закрыта|платн)[^)]*\)/gi, ' ');

  // 3) Чанки: режем по декоративным разделителям и границам предложений.
  const chunks = s
    .replace(SEPARATOR_RE, '\u2023')
    .split(/\u2023|(?<=[.!?…])\s+/)
    .map(c => c.trim())
    .filter(Boolean);

  // 4) В каждом чанке срезаем футер от ключевого слова до конца чанка.
  const kept: string[] = [];
  for (let chunk of chunks) {
    for (const kw of FOOTER_KEYWORDS) {
      const re = new RegExp(kw + '.*$', 'i');
      if (re.test(chunk)) chunk = chunk.replace(re, '').trim();
      if (!chunk) break;
    }
    chunk = chunk
      .replace(/\s+/g, ' ')
      .replace(/^[|·—–:;,\s]+/, '')
      .replace(/[|·—–:;,\s]+$/, '')
      .trim();
    if (chunk.length < 2) continue;              // пусто/мусор
    if (!HAS_WORDCHAR_RE.test(chunk)) continue;  // только эмодзи/пунктуация
    if (/[:\uFF1A]$/.test(chunk)) continue;      // висящий вводный хвост «…:»
    if (CHUNK_DROP_RE.some(re => re.test(chunk))) continue; // атрибуция-остатки
    kept.push(chunk);
  }

  // 5) Склейка + финальная уборка.
  let out = kept.join(' ').replace(/\s+/g, ' ').trim();
  out = out.replace(/\s*([.!?…])\s*/g, '$1 ');   // пробелы после терм. знаков
  out = out.replace(/\s+$/, '').trim();
  return out.slice(0, 600);
}
